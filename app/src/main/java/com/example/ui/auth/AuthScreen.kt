            }

            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text(
                    text = stringResource(R.string.auth_headline),
                    style = MaterialTheme.typography.displaySmall,
                    color = MaterialTheme.colorScheme.onBackground
                )
                Text(
                    text = stringResource(R.string.auth_subheadline),
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }

            Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                AuthFeatureRow(
                    icon = Icons.Default.CloudOff,
                    title = "Offline Library",
                    subtitle = "Download full multi-chapter classics to read anywhere"
                )
                AuthFeatureRow(
                    icon = Icons.Default.DarkMode,
                    title = "Night Mode & Paper Themes",
                    subtitle = "Switch between Ivory Paper, Sepia, Night Ink, and OLED"
                )
                AuthFeatureRow(
                    icon = Icons.Default.Group,
                    title = "Shared Book Links",
                    subtitle = "Send a link so friends can read and track chapters with you"
                )
            }

            if (errorMessage != null) {
                Surface(
                    shape = RoundedCornerShape(14.dp),
                    color = MaterialTheme.colorScheme.errorContainer
                ) {
